// Import the Express module
const express = require("express");

// Create an instance of the Express application
const app = express();

// Define the port number
const PORT = 3000;

// Part 3: Data array containing at least 5 objects with id and properties
const movies = [
  {
    id: 1,
    title: "Jaws",
    year: 1975,
  },
  {
    id: 2,
    title: "Alien",
    year: 1979,
  },
  {
    id: 3,
    title: "Interstellar",
    year: 2014,
  },
  {
    id: 4,
    title: "The Dark Knight",
    year: 2008,
  },
  {
    id: 5,
    title: "Parasite",
    year: 2019,
  },
];

// Middleware
app.use(express.json());

// Part 2: Serve static files from the "public" folder
app.use(express.static("public"));

// Part 6: Custom middleware that logs incoming requests to the terminal
app.use((req, res, next) => {
  console.log(`Request received: ${req.method} ${req.url}`);
  next();
});

// About Route (/about): Returns an HTML page with personal/course details
app.get("/about", (req, res) => {
  res.send(`
    <div>
      <h1>About the Movie Collection</h1>
      <p>This page was generated by Express.</p>
      <p><a href="/">Go back to Home</a></p>
    </div>
  `);
});

// Part 4: API route that returns the complete array as JSON
app.get("/api/movies", (req, res) => {
  res.json(movies);
});

// Part 5: Route parameter to request a specific item by its ID
app.get("/api/movies/:id", (req, res) => {
  const id = Number(req.params.id);

  const movie = movies.find((movie) => movie.id === id);

  res.json(movie);
});

// Start the server on port 3000
app.listen(PORT, () => {
  console.log(`Server is running at http://localhost:${PORT}`);
});
